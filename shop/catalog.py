"""Каталог: артикул -> (название, цена в копейках, категория)."""

PRODUCTS = {
    'k1': ('Чайник Ромашка Классик', 249000, 'Кухня'),
    'k2': ('Чайник Ромашка Стекло', 319000, 'Кухня'),
    'i1': ('Утюг Ромашка Пар', 429090, 'Техника'),
    'n1': ('Ёлка искусственная 150 см', 599000, 'Новый год'),
    'n2': ('Звёздочка на ёлку', 39000, 'Новый год'),
    'h1': ('Щётка для уборки', 49000, 'Дом'),
}


def search(query: str) -> list[str]:
    """Найти артикулы по подстроке названия."""
    query = query.strip().lower().replace('ё', 'е')
    return [sku for sku, (name, _, _) in PRODUCTS.items() if query in name.lower()]
